export const NEPALI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'] as const;

export function toNepaliDigits(val: number | string): string {
  return String(val).replace(/\d/g, (d) => NEPALI_DIGITS[parseInt(d, 10)]);
}

export function fromNepaliDigits(val: string): string {
  return String(val).replace(/[०-९]/g, (d) => String(NEPALI_DIGITS.indexOf(d as any)));
}

